def _load_encryption_key():
    key = os.environ.get("FIELD_ENCRYPTION_KEY", "").strip()
    if not key:
        raise ImproperlyConfigured(
            "FIELD_ENCRYPTION_KEY mungon. Gjenero një çelës me: "
            'python -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"'
        )
    try:
        from cryptography.fernet import Fernet

        Fernet(key.encode("utf-8"))
    except Exception as exc:
        raise ImproperlyConfigured("FIELD_ENCRYPTION_KEY duhet të jetë një çelës Fernet.") from exc
    return key


FIELD_ENCRYPTION_KEY = _load_encryption_key()

